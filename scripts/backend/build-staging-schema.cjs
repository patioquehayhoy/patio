// Restores public DDL and Storage policy metadata only, never production users.
const fs=require('node:fs');
const schema=require('./schema-2026-10-09.json');
const inventory=require('./inventory-2026-10-09.json');
const q=s=>'"'+s.replaceAll('"','""')+'"';
const out=['begin;'];
for(const t of inventory.tables){
 const columns=schema.columns.filter(c=>c.table_name===t.name).sort((a,b)=>a.ordinal_position-b.ordinal_position);
 out.push(`create table public.${q(t.name)} (${columns.map(c=>`${q(c.column_name)} ${c.data_type==='ARRAY'?c.udt_name.slice(1)+'[]':c.data_type}${c.is_identity==='YES'?' generated by default as identity':c.column_default?' default '+c.column_default:''}${c.is_nullable==='NO'?' not null':''}`).join(',')});`);
}
for(const fk of [false,true]) for(const c of schema.constraints.filter(c=>c.definition.startsWith('FOREIGN KEY')===fk)) out.push(`alter table public.${q(c.table)} add constraint ${q(c.name)} ${c.definition};`);
for(const i of schema.indexes) if(!schema.constraints.some(c=>c.table===i.tablename&&c.name===i.indexname)) out.push(i.indexdef+';');
for(const f of schema.functions) out.push(f.definition+';');
for(const t of schema.triggers) out.push(t.definition+';');
for(const t of inventory.tables) if(t.rls) out.push(`alter table public.${q(t.name)} enable row level security;`);
for(const p of inventory.policies) out.push(`create policy ${q(p.policyname)} on ${q(p.schemaname)}.${q(p.tablename)} as ${p.permissive} for ${p.cmd} to ${p.roles.map(q).join(',')}${p.qual?' using ('+p.qual+')':''}${p.with_check?' with check ('+p.with_check+')':''};`);
for(const b of inventory.buckets) out.push(`insert into storage.buckets(id,name,public) values('${b.name.replaceAll("'","''")}','${b.name.replaceAll("'","''")}',${b.public});`);
out.push('grant select,insert,update,delete on all tables in schema public to anon,authenticated,service_role;');
out.push('grant usage,select on all sequences in schema public to authenticated,service_role;');
out.push('commit;');
fs.writeFileSync(process.argv[2],out.join('\n'));
console.log('DDL staging generado: esquema público y políticas Storage, sin datos de producción.');
